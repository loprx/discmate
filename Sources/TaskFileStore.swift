import Foundation
import Darwin

/// Serial, ordered task text logging. File I/O never runs on the UI actor.
final class TaskFileStore: @unchecked Sendable {
    private let queue = DispatchQueue(label: "local.discmate.task-files", qos: .utility)

    func append(_ line: String, to url: URL, failure: @escaping (Error) -> Void) {
        queue.async {
            do {
                let descriptor = url.path.withCString { open($0, O_WRONLY | O_CREAT | O_APPEND, 0o600) }
                guard descriptor >= 0 else { throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno)) }
                defer { _ = close(descriptor) }
                guard fchmod(descriptor, 0o600) == 0 else { throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno)) }
                try Data(line.utf8).withUnsafeBytes { bytes in
                    var offset = 0
                    while offset < bytes.count {
                        let written = Darwin.write(descriptor, bytes.baseAddress!.advanced(by: offset), bytes.count - offset)
                        if written < 0 && errno == EINTR { continue }
                        guard written > 0 else { throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno)) }
                        offset += written
                    }
                }
            } catch { failure(error) }
        }
    }

    func flush() async {
        await withCheckedContinuation { continuation in
            queue.async { continuation.resume() }
        }
    }

    /// Only directories generated by IncrementalISO may be removed here.
    func discardImageDirectory(containing image: URL, failure: @escaping (Error) -> Void = { _ in }) {
        let directory = image.deletingLastPathComponent()
        let temporary = FileManager.default.temporaryDirectory.standardizedFileURL
        guard directory.deletingLastPathComponent().standardizedFileURL == temporary,
              directory.lastPathComponent.hasPrefix("discmate-incremental-") else { return }
        queue.async {
            do { try FileManager.default.removeItem(at: directory) }
            catch { failure(error) }
        }
    }
}
